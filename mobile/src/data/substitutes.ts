export function substitutesFor(name: string): string[] {
  const lower = name.toLowerCase();
  const match = SUBSTITUTES.find(([pattern]) => pattern.test(lower));
  return (match?.[1] ?? []).filter(option => option.toLowerCase() !== lower);
}
